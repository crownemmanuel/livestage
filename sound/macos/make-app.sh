#!/bin/bash
# Makes "LiveStage Sound.app" in ~/Applications: a double-clickable launcher for this checkout.
# It runs `node sound/launch.ts` (builds the screens if needed, starts the service unless it is already
# running, opens the operator window). Run it yourself once:  bash sound/macos/make-app.sh
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
NODE="$(command -v node || true)"
if [ -z "$NODE" ]; then echo "node is not on PATH: install Node 26 first" >&2; exit 1; fi
APP="$HOME/Applications/LiveStage Sound.app"
LOGDIR="$HOME/Library/Logs/LiveStage Sound"

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$LOGDIR"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>LiveStage Sound</string>
  <key>CFBundleDisplayName</key><string>LiveStage Sound</string>
  <key>CFBundleIdentifier</key><string>org.salvation.livestage-sound.launcher</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.1</string>
  <key>LSUIElement</key><true/>
</dict></plist>
PLIST
cat > "$APP/Contents/MacOS/launch" <<SH
#!/bin/bash
# Generated by sound/macos/make-app.sh for $REPO
cd "$REPO"
exec "$NODE" sound/launch.ts >> "$LOGDIR/launcher.log" 2>&1
SH
chmod +x "$APP/Contents/MacOS/launch"
echo "Made $APP"
echo "Logs: $LOGDIR/launcher.log (the service also logs to ~/Library/Application Support/LiveStage Sound/sound.log)"
